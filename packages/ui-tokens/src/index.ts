export type TokenName = keyof typeof light;

function block(selector: string, scheme: 'light' | 'dark', map: Record<string, string>, indent = ''): string {
  const lines = Object.entries(map).map(([name, value]) => `${indent}  ${name}: ${value};`);
  return [`${indent}${selector} {`, `${indent}  color-scheme: ${scheme};`, ...lines, `${indent}}`].join('\n');
}

/**
 * The stylesheet the web app imports.
 *
 * The dark palette is emitted twice on purpose: the theme toggle has to beat
 * the OS preference in both directions, so one copy sits under
 * prefers-color-scheme guarded by :not([data-theme="light"]) and one under
 * [data-theme="dark"]. Generating both from `dark` is what stops them diverging.
 */
export function tokensCss(): string {
  return [
    '/* GENERATED by @paathshala/ui-tokens. Do not edit; change packages/ui-tokens/src/index.ts',
    '   and run: pnpm --filter @paathshala/ui-tokens emit */',
    '',
    block(':root', 'light', light),
    '',
    '@media (prefers-color-scheme: dark) {',
    block(':root:not([data-theme="light"])', 'dark', dark, '  '),
    '}',
    '',
    block(':root[data-theme="dark"]', 'dark', dark),
    '',
  ].join('\n');
}

